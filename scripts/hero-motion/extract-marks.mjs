#!/usr/bin/env node
/**
 * Regenerates lib/hero-motion/marks.js from components/icons/brand-marks.tsx.
 *
 * The hero motion scene is plain ESM JavaScript (it is loaded both by Next and
 * by the standalone render page in this folder), so it cannot import the .tsx
 * file directly. This copies BRAND_MARK_PATHS verbatim (path data, viewBox,
 * origin, evenodd) into a generated module. Re-run after editing brand marks:
 *
 *   node scripts/hero-motion/extract-marks.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const src = readFileSync(resolve(root, "components/icons/brand-marks.tsx"), "utf8");

const head = "export const BRAND_MARK_PATHS: Record<string, BrandMark> = ";
const start = src.indexOf(head);
if (start < 0) throw new Error("BRAND_MARK_PATHS not found");
const bodyStart = start + head.length;
const end = src.indexOf("\n};", bodyStart);
if (end < 0) throw new Error("end of BRAND_MARK_PATHS not found");
const literal = src.slice(bodyStart, end + 2);

// The literal is plain JS (string/number/array/object, comments). Evaluate it.
const marks = new Function(`return (${literal});`)();

// --- AiIcons.tsx: the marks the site draws first (see getToolIcon) ---------
// Only icons made purely of filled <path> elements are copied (drawn in one
// colour, as on the site with currentColor); icons with strokes, rects,
// circles or groups are skipped and fall back to brand-marks / monograms.
const aiSrc = readFileSync(resolve(root, "components/icons/AiIcons.tsx"), "utf8");
/** @type {Record<string, { viewBox: [number, number], paths: string[] }>} */
const byComponent = {};
const fnRe = /export function (\w+)\([^)]*\)[^{]*\{([\s\S]*?)\n\}/g;
for (const [, name, body] of aiSrc.matchAll(fnRe)) {
  const svg = /<svg[^>]*viewBox="([^"]+)"/.exec(body);
  if (!svg) continue;
  const elements = [...body.matchAll(/<(path|rect|circle|g|ellipse|line|polygon|text)\b([^>]*)>/g)];
  const ok = elements.length > 0 && elements.every(([, tag, attrs]) => tag === "path" && !/stroke|fill="none"/.test(attrs));
  if (!ok) continue;
  const [, , w, h] = svg[1].split(/\s+/).map(Number);
  byComponent[name] = {
    viewBox: [w, h],
    paths: elements.map(([, , attrs]) => /\bd="([^"]+)"/.exec(attrs)[1]),
  };
}

// Slug resolution copied from components/icons/tool-icons.tsx.
const tiSrc = readFileSync(resolve(root, "components/icons/tool-icons.tsx"), "utf8");
const block = (label) => {
  const at = tiSrc.indexOf(label);
  if (at < 0) throw new Error(`${label} not found in tool-icons.tsx`);
  const open = tiSrc.indexOf("{", at);
  return tiSrc.slice(open, tiSrc.indexOf("};", open) + 1);
};
const baseMap = Object.fromEntries(
  [...block("const baseIconMap").matchAll(/^\s*"?([\w-]+)"?\s*:\s*(\w+)/gm)].map(([, k, v]) => [k, v]),
);
const aliases = Object.fromEntries(
  [...block("const iconAliases").matchAll(/^\s*"?([\w-]+)"?\s*:\s*"([\w-]+)"/gm)].map(([, k, v]) => [k, v]),
);
/** @type {Record<string, { viewBox: [number, number], paths: string[] }>} */
const aiMarks = {};
for (const [key, component] of Object.entries(baseMap)) {
  if (byComponent[component]) aiMarks[key] = byComponent[component];
}

const out = `// GENERATED by scripts/hero-motion/extract-marks.mjs from
// components/icons/brand-marks.tsx, components/icons/AiIcons.tsx and the
// slug resolution in components/icons/tool-icons.tsx - do not edit by hand.
// Path data is copied verbatim; sources and licences are listed in those
// files (simple-icons CC0-1.0, @lobehub/icons-static-svg MIT,
// @iconify-json/logos CC0-1.0, and the owners' official brand assets).
// Brand names and logos are trademarks of their owners.

/** @typedef {{ viewBox?: [number, number], origin?: [number, number], evenodd?: boolean, paths: string[] }} BrandMark */

/** @type {Record<string, BrandMark>} */
export const BRAND_MARK_PATHS = ${JSON.stringify(marks, null, 2)};

/** AiIcons.tsx marks keyed like baseIconMap in tool-icons.tsx (single colour). */
/** @type {Record<string, BrandMark>} */
export const AI_ICON_PATHS = ${JSON.stringify(aiMarks, null, 2)};

/** iconAliases from tool-icons.tsx. */
/** @type {Record<string, string>} */
export const ICON_ALIASES = ${JSON.stringify(aliases, null, 2)};

/**
 * Same order as getToolIcon(): AiIcons by key, alias, then "key-" prefix,
 * then brand-marks.tsx; null means the monogram tile.
 * @param {string} slug
 * @returns {BrandMark | null}
 */
export function markForSlug(slug) {
  const s = slug.toLowerCase();
  if (AI_ICON_PATHS[s]) return AI_ICON_PATHS[s];
  const alias = ICON_ALIASES[s];
  if (alias && AI_ICON_PATHS[alias]) return AI_ICON_PATHS[alias];
  for (const key of Object.keys(AI_ICON_PATHS)) {
    if (s.startsWith(key + "-")) return AI_ICON_PATHS[key];
  }
  return BRAND_MARK_PATHS[s] || null;
}
`;
writeFileSync(resolve(root, "lib/hero-motion/marks.js"), out);
console.log(
  `wrote lib/hero-motion/marks.js (${Object.keys(marks).length} brand marks, ` +
    `${Object.keys(aiMarks).length} AiIcons marks: ${Object.keys(aiMarks).join(" ")}; skipped ` +
    `${Object.values(baseMap).filter((c) => !byComponent[c]).join(" ") || "none"})`,
);
